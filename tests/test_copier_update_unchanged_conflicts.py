"""A conflict on a file the project never edited resolves to the new template version.

Copier renders the *old* copy of the template with the *new* template's ``_exclude``
rules. When the new template excludes a file behind a question the old template never
declared, the old copy lacks the file, Copier reads the update as "file added", and it
conflicts with the identical file already in the project. These tests use real Copier,
real Git and a real two-commit template that crosses that boundary.
"""

import shutil
import subprocess
from pathlib import Path

import pytest
import yaml

from ai_cli.copier_update import EX_PARTIAL_MUTATION, CopierUpdateInspection, run_copier_update

_GUARD_V1 = "LIMIT = 1\n\n\ndef limit() -> int:\n    return LIMIT\n"
_GUARD_V2 = "LIMIT = 2\n\n\ndef limit() -> int:\n    return LIMIT\n"

_CONFIG_V1 = "_subdirectory: template\nproject_name:\n  type: str\n  default: myproject\n"
# The second template version adds a hidden question and excludes the guard unless it is true,
# the same shape as a template that ships a test plugin only to repos with Python tests.
_CONFIG_V2 = (
    _CONFIG_V1 + "include_guard:\n  type: bool\n  default: true\n  ask: false\n"
    "_exclude:\n"
    '  - "{% if not include_guard %}guard.py{% endif %}"\n'
)


@pytest.fixture(autouse=True)
def _no_issue_tracker(monkeypatch):
    """The fixture projects have no issue store; filing is covered by the recovery tests."""
    monkeypatch.setattr("ai_cli.copier_update._file_recovery_issue", lambda *args, **kwargs: "issue-1")


# A template that ships a test plugin and its test, excluded for a repo without Python
# tests, behind a hidden question the recorded template version predates.
_FLEET_CONFIG_V1 = _CONFIG_V1 + "tech_stack:\n  type: str\n  default: python\n"
_FLEET_CONFIG_V2 = (
    _FLEET_CONFIG_V1 + "include_python_tests:\n  type: bool\n  default: true\n  ask: false\n"
    "_exclude:\n"
    "  - \"{% if 'python' not in tech_stack or not include_python_tests %}guard_plugin.py{% endif %}\"\n"
    "  - \"{% if 'python' not in tech_stack or not include_python_tests %}tests/test_guard_plugin.py"
    '{% endif %}"\n'
)


def _run(cwd: Path, *args: str) -> str:
    result = subprocess.run(args, cwd=cwd, check=True, capture_output=True, text=True)
    return result.stdout.strip()


def _commit_all(repo: Path, message: str) -> None:
    _run(repo, "git", "add", "-A")
    _run(repo, "git", "commit", "-qm", message)


def _make_projects(
    tmp_path: Path,
    *,
    edit_guard: str | None = None,
    edit_message: bool = False,
    fleet_shape: bool = False,
    crlf_template: bool = False,
) -> Path:
    """Build a project recorded at template version 1 whose template tip is version 2."""

    def guard_text(text: str) -> bytes:
        return text.replace("\n", "\r\n").encode() if crlf_template else text.encode()

    guard_paths = ("guard_plugin.py", "tests/test_guard_plugin.py") if fleet_shape else ("guard.py",)
    config_v1, config_v2 = (_FLEET_CONFIG_V1, _FLEET_CONFIG_V2) if fleet_shape else (_CONFIG_V1, _CONFIG_V2)
    author = tmp_path / "template-author"
    projects = tmp_path / "projects"
    local_template = projects / "project-template"
    project = projects / "myproject"
    author.mkdir()
    projects.mkdir()

    _run(tmp_path, "git", "init", "-q", "--initial-branch=main", str(author))
    _run(author, "git", "config", "user.email", "test@example.com")
    _run(author, "git", "config", "user.name", "Test User")
    (author / "copier.yml").write_text(config_v1)
    (author / "template").mkdir()
    (author / "template" / ".copier-answers.yml.jinja").write_text(
        "# Generated by Copier\n{{ _copier_answers|to_nice_yaml -}}\n"
    )
    for guard in guard_paths:
        (author / "template" / guard).parent.mkdir(parents=True, exist_ok=True)
        (author / "template" / guard).write_bytes(guard_text(_GUARD_V1))
    (author / "template" / "message.txt").write_text("original\n")
    _commit_all(author, "version 1")

    _run(tmp_path, "git", "clone", "-q", str(author), str(local_template))
    copier_bin = shutil.which("copier")
    assert copier_bin is not None
    subprocess.run(
        [copier_bin, "copy", "--trust", "--defaults", str(local_template), str(project)],
        check=True,
        capture_output=True,
        text=True,
    )
    recorded = yaml.safe_load((project / ".copier-answers.yml").read_text())
    assert "include_guard" not in recorded
    assert "include_python_tests" not in recorded

    _run(project, "git", "init", "-q", "--initial-branch=main")
    if crlf_template:
        # What a Windows checkout does: Git stores the file with LF while Copier renders it with CRLF.
        (project / ".gitattributes").write_text("*.py text\n")
    _run(project, "git", "config", "user.email", "test@example.com")
    _run(project, "git", "config", "user.name", "Test User")
    _run(project, "git", "add", "-A")
    _run(project, "git", "commit", "-qm", "initial")
    if edit_guard is not None:
        (project / guard_paths[0]).write_text(edit_guard)
    if edit_message:
        (project / "message.txt").write_text("project customization\n")
    if edit_guard is not None or edit_message:
        _commit_all(project, "local edits")

    (author / "copier.yml").write_text(config_v2)
    for guard in guard_paths:
        (author / "template" / guard).write_bytes(guard_text(_GUARD_V2))
    (author / "template" / "message.txt").write_text("template update\n")
    _commit_all(author, "version 2")
    _run(local_template, "git", "pull", "-q", "--ff-only")
    return projects


def _inspect(projects: Path) -> CopierUpdateInspection:
    result = run_copier_update(projects_dir=projects, isolate=True, push=False, inspect=True)
    assert isinstance(result, CopierUpdateInspection)
    return result


def _anchors(project: Path) -> list[str]:
    refs = _run(project, "git", "for-each-ref", "--format=%(refname)", "refs/backup")
    return [ref for ref in refs.splitlines() if "/copier-update/myproject-" in ref]


def test_given_unedited_file_when_update_conflicts_then_new_template_version_is_taken(tmp_path, capsys):
    projects = _make_projects(tmp_path)

    result = _inspect(projects)

    assert result.exit_code == 0
    (delivered,) = result.delivered_updates
    assert delivered.changed_files["guard.py"].replace(b"\r\n", b"\n") == _GUARD_V2.encode()
    out = capsys.readouterr().out
    assert "auto-resolved" in out
    assert "guard.py" in out
    assert "CONFLICTS" not in out


def test_given_auto_resolved_file_when_update_runs_then_a_backup_anchor_is_kept(tmp_path):
    projects = _make_projects(tmp_path)

    _inspect(projects)

    (anchor,) = _anchors(projects / "myproject")
    snapshot = _run(projects / "myproject", "git", "show", f"{anchor}:guard.py")
    # The snapshot is taken before the file is rewritten, so it still holds the conflict.
    assert "<<<<<<<" in snapshot


def test_given_file_edited_by_one_byte_when_update_conflicts_then_it_stays_a_conflict(tmp_path, capsys):
    projects = _make_projects(tmp_path, edit_guard=_GUARD_V1 + " ")

    result = run_copier_update(projects_dir=projects, isolate=True, push=False)

    assert result == EX_PARTIAL_MUTATION
    out = capsys.readouterr().out
    assert "conflict: guard.py" in out
    assert "auto-resolved" not in out


def test_given_one_edited_and_one_unedited_conflict_when_updating_then_only_the_edited_one_is_reported(
    tmp_path, capsys
):
    projects = _make_projects(tmp_path, edit_message=True)

    result = run_copier_update(projects_dir=projects, isolate=True, push=False)

    assert result == EX_PARTIAL_MUTATION
    out = capsys.readouterr().out
    assert "conflict: message.txt" in out
    assert "conflict: guard.py" not in out
    assert "auto-resolved" in out
    assert "guard.py" in out


@pytest.mark.parametrize("edit", [None, _GUARD_V1 + " "], ids=["unedited", "edited"])
def test_given_any_outcome_when_updating_then_the_project_main_tree_is_untouched(tmp_path, edit):
    projects = _make_projects(tmp_path, edit_guard=edit)
    before = (projects / "myproject" / "guard.py").read_text()

    run_copier_update(projects_dir=projects, isolate=True, push=False)

    assert (projects / "myproject" / "guard.py").read_text() == before


def test_given_plugin_excluded_by_hidden_question_when_updating_then_both_files_take_the_new_version(tmp_path, capsys):
    projects = _make_projects(tmp_path, fleet_shape=True)

    result = _inspect(projects)

    assert result.exit_code == 0
    (delivered,) = result.delivered_updates
    assert delivered.changed_files["guard_plugin.py"].replace(b"\r\n", b"\n") == _GUARD_V2.encode()
    assert delivered.changed_files["tests/test_guard_plugin.py"].replace(b"\r\n", b"\n") == _GUARD_V2.encode()
    out = capsys.readouterr().out
    assert "auto-resolved (unchanged since the previous template): guard_plugin.py" in out
    assert "auto-resolved (unchanged since the previous template): tests/test_guard_plugin.py" in out


def test_given_rendered_copy_with_other_line_endings_when_update_conflicts_then_the_file_still_resolves(
    tmp_path, capsys
):
    projects = _make_projects(tmp_path, crlf_template=True)

    result = _inspect(projects)

    assert result.exit_code == 0
    (delivered,) = result.delivered_updates
    assert delivered.changed_files["guard.py"].replace(b"\r\n", b"\n") == _GUARD_V2.encode()
    assert "auto-resolved" in capsys.readouterr().out
