"""A template change that only moves whitespace is not a missing file in the parity check.

A template commit can change nothing but whitespace or Jinja whitespace control, for example a
trailing blank line. A project whose own formatter already removed that line gets no file change
from Copier, which is correct. The parity check must not call that file missing.
"""

import shutil
import subprocess
from pathlib import Path
from unittest.mock import patch

import pytest

from ai_cli.copier_update import EX_PARTIAL_MUTATION, CopierUpdateInspection, run_copier_update

_CONFIG = "_subdirectory: template\nproject_name:\n  type: str\n  default: myproject\nflag:\n  type: bool\n  default: false\n  ask: false\n"
_BEFORE = "key: 1\n{% if flag %}\nextra: 2\n{% endif %}\n"
_WHITESPACE_ONLY = "key: 1\n{%- if flag %}\nextra: 2\n{%- endif %}\n"
_REAL_CHANGE = "key: 9\n{%- if flag %}\nextra: 2\n{%- endif %}\n"


@pytest.fixture(autouse=True)
def _no_issue_tracker(monkeypatch):
    """The fixture projects have no issue store; filing is covered by the recovery tests."""
    monkeypatch.setattr("ai_cli.copier_update._file_recovery_issue", lambda *args, **kwargs: "issue-1")


def _run(cwd: Path, *args: str) -> str:
    return subprocess.run(args, cwd=cwd, check=True, capture_output=True, text=True).stdout.strip()


def _commit_all(repo: Path, message: str) -> None:
    _run(repo, "git", "add", "-A")
    _run(repo, "git", "commit", "-qm", message)


def _make_projects(tmp_path: Path, template_after: str, project_content: str | None) -> Path:
    """A project recorded at template version 1; ``project_content`` is what its own formatter left."""
    author = tmp_path / "template-author"
    projects = tmp_path / "projects"
    local_template = projects / "project-template"
    project = projects / "myproject"
    author.mkdir()
    projects.mkdir()
    _run(tmp_path, "git", "init", "-q", "--initial-branch=main", str(author))
    _run(author, "git", "config", "user.email", "test@example.com")
    _run(author, "git", "config", "user.name", "Test User")
    (author / "copier.yml").write_text(_CONFIG)
    (author / "template").mkdir()
    (author / "template" / ".copier-answers.yml.jinja").write_text(
        "# Generated by Copier\n{{ _copier_answers|to_nice_yaml -}}\n"
    )
    (author / "template" / "config.yaml.jinja").write_text(_BEFORE)
    _commit_all(author, "version 1")
    _run(tmp_path, "git", "clone", "-q", str(author), str(local_template))
    copier_bin = shutil.which("copier")
    assert copier_bin is not None
    subprocess.run(
        [copier_bin, "copy", "--trust", "--defaults", str(local_template), str(project)],
        check=True,
        capture_output=True,
        text=True,
    )
    _run(project, "git", "init", "-q", "--initial-branch=main")
    _run(project, "git", "config", "user.email", "test@example.com")
    _run(project, "git", "config", "user.name", "Test User")
    _run(project, "git", "add", "-A")
    _run(project, "git", "commit", "-qm", "initial")
    if project_content is not None:
        (project / "config.yaml").write_text(project_content)
        _commit_all(project, "formatter trims the file")
    (author / "template" / "config.yaml.jinja").write_text(template_after)
    _commit_all(author, "version 2")
    _run(local_template, "git", "pull", "-q", "--ff-only")
    return projects


def test_given_whitespace_only_template_change_when_project_already_trimmed_then_parity_does_not_fail(tmp_path, capsys):
    projects = _make_projects(tmp_path, _WHITESPACE_ONLY, "key: 1\n")

    result = run_copier_update(projects_dir=projects, isolate=True, push=False, inspect=True)

    assert isinstance(result, CopierUpdateInspection)
    assert result.exit_code == 0
    assert "parity failed" not in capsys.readouterr().out


def test_given_content_change_that_copier_leaves_out_when_updating_then_parity_still_names_the_file(tmp_path, capsys):
    projects = _make_projects(tmp_path, _REAL_CHANGE, None)
    project = projects / "myproject"
    real_run = subprocess.run
    copier_bin = shutil.which("copier")
    original = (project / "config.yaml").read_text()

    def copier_that_drops_the_change(command, **kwargs):
        result = real_run(command, **kwargs)
        if command[0] == copier_bin and command[1:2] == ["update"]:
            (project / "config.yaml").write_text(original)
        return result

    with patch("ai_cli.copier_update.subprocess.run", side_effect=copier_that_drops_the_change):
        result = run_copier_update(projects_dir=projects, isolate=False)

    assert result == EX_PARTIAL_MUTATION
    assert "missing changed file(s): config.yaml" in capsys.readouterr().out
